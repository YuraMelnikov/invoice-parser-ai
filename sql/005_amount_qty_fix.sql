-- ============================================================
-- Задача 005 / ADR-0006: контроль «стоимость / количество = цена»
-- amount  — стоимость позиции без НДС (колонка «Стоимость» накладной)
-- qty_fix — аудит каскада коррекции количества:
--   1  = amount/qty сошлось с price без правки
--   1000/100/10 = количество исправлено этим делителем
--   -1 = не сошлось ни с одним делителем, оставлено как есть
--   0  = проверка не выполнялась (нет qty/price/amount или нули;
--        также у всех строк, записанных до этой миграции)
-- Идемпотентно: повторный накат безопасен.
-- ============================================================

ALTER TABLE docs.invoice_items
    ADD COLUMN IF NOT EXISTS amount numeric(14, 2);

ALTER TABLE docs.invoice_items
    ADD COLUMN IF NOT EXISTS qty_fix smallint NOT NULL DEFAULT 0;
